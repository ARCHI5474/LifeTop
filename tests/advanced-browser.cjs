const assert = require('node:assert/strict');
const { withApp, openGames, selectGame } = require('./helpers/browser.cjs');

withApp(async page => {
    await page.locator('[aria-label="Quickパネル"]').click();
    await page.locator('#settings-tab-advanced').click();
    await page.locator('.advanced-settings summary').click();
    await page.locator('#advanced-searchEngine input[value=yahoo]').check();
    await page.locator('#advanced-searchShape input[value=square]').check();
    await page.locator('#advanced-reduceMotion').check();
    await page.locator('#advanced-hideClockBackground').check();
    await page.locator('#clock-show-sec-toggle').check();
    await page.locator('#settings-tab-profile').click();
    await page.locator('#username-input').fill('テストユーザー');
    await page.locator('[data-profile-icon=star]').click();
    await page.reload();
    await page.locator('#loading-screen').waitFor({state:'detached'});
    assert.equal(await page.locator('#search-input').getAttribute('name'), 'p');
    assert.equal(await page.locator('#search-form').getAttribute('action'), 'https://search.yahoo.co.jp/search');
    assert.equal(await page.locator('#search-form').evaluate(e => getComputedStyle(e).borderRadius), '0px');
    assert.equal(await page.locator('html').evaluate(e => e.classList.contains('reduce-motion')), true);
    assert.equal(await page.locator('#clock-sec').isVisible(), true);
    assert.equal(await page.locator('#header-user-name').innerText(), 'テストユーザー');
    await page.locator('[aria-label="Quickパネル"]').click();
    await page.locator('#settings-tab-advanced').click();
    await page.locator('.advanced-settings summary').click();
    await page.locator('#advanced-reset').click();
    assert.equal(await page.locator('#advanced-searchEngine input:checked').inputValue(), 'google');
    assert.equal(await page.locator('#advanced-searchShape input:checked').inputValue(), 'pill');
    assert.equal(await page.locator('#advanced-reduceMotion').isChecked(), false);
    assert.equal(await page.locator('#username-input').inputValue(), 'テストユーザー');
    assert.equal(await page.locator('#user-badge [data-icon]').getAttribute('data-icon'), 'star');
    await page.keyboard.press('Escape');
    for (const width of [320,390,768,1440]) {
        await page.setViewportSize({width,height:844});
        await page.locator('[aria-label="Quickパネル"]').click();
        assert.equal(await page.locator('.settings-body').evaluate(e => e.scrollWidth <= e.clientWidth + 1), true);
        await page.keyboard.press('Escape');
    }
    await openGames(page);
    await selectGame(page, 'go');
    await page.locator('#go-board [data-cell="40"]').click();
    assert.match(await page.locator('#go-status').innerText(), /白の番/);
    await page.locator('#go-undo').click();
    assert.equal(await page.locator('#go-board [data-cell="40"]').innerText(), '·');
    await page.locator('#go-pass').click();
    await page.locator('#go-pass').click();
    assert.match(await page.locator('#go-status').innerText(), /終局/);
    await selectGame(page, 'shogi');
    await page.locator('#shogi-board [data-cell="54"]').click();
    await page.locator('#shogi-board [data-cell="45"]').click();
    assert.match(await page.locator('#shogi-status').innerText(), /後手/);
    await page.locator('#shogi-undo').click();
    assert.equal(await page.locator('#shogi-board [data-cell="54"]').innerText(), '歩');
    await selectGame(page, 'hitblow');
    await page.locator('#hit-input').fill('0012');
    await page.locator('#hit-submit').click();
    assert.match(await page.locator('#hit-status').innerText(), /異なる/);
    await page.locator('#hit-input').fill('0123');
    await page.locator('#hit-submit').click();
    assert.equal(await page.locator('#hit-history tr').count(), 1);
    console.log('PASS: advanced settings persistence/reset, profile preservation, responsive settings, Go/Shogi undo and guess validation');
}).catch(error => {console.error(error); process.exitCode=1;});
