const assert = require('node:assert/strict');
const { withApp } = require('./helpers/browser.cjs');

withApp(async page => {
    await page.evaluate(() => {
        const original = Storage.prototype.setItem;
        window.rejectHomeSave = true;
        Storage.prototype.setItem = function(key, value) {
            if (key === 'lifetop_v1_0_data' && window.rejectHomeSave) throw new DOMException('quota', 'QuotaExceededError');
            return original.call(this, key, value);
        };
    });
    const tasks = () => page.evaluate(async () => structuredClone((await import('./js/config.js?v=9.0')).userConfig.todoList));
    const before = await tasks();
    await page.locator('#todo-input').fill('保存失敗でも入力を維持');
    await page.locator('#todo-input').press('Enter');
    assert.equal(await page.locator('#todo-input').inputValue(), '保存失敗でも入力を維持');
    assert.deepEqual(await tasks(), before, 'failed task creation leaves state unchanged');
    await page.evaluate(() => window.rejectHomeSave = false);
    await page.locator('#todo-input').press('Enter');
    const checkbox = page.getByRole('checkbox', { name: '保存失敗でも入力を維持', exact: true });
    await page.evaluate(() => window.rejectHomeSave = true);
    await checkbox.click();
    assert.equal(await checkbox.isChecked(), false, 'failed completion restores the checkbox');
    await page.locator('[aria-label="保存失敗でも入力を維持を削除"]').click();
    assert.equal(await checkbox.count(), 1, 'failed deletion preserves the task');
    await page.evaluate(() => window.rejectHomeSave = false);
    await page.locator('[aria-label="保存失敗でも入力を維持を削除"]').click();
    await page.evaluate(() => window.rejectHomeSave = true);
    await page.locator('#todo-undo button').click();
    assert.equal(await checkbox.count(), 0);
    assert.equal(await page.locator('#todo-undo').isVisible(), true, 'failed undo remains retryable');
    await page.evaluate(() => window.rejectHomeSave = false);
    await page.locator('#todo-undo button').click();
    assert.equal(await checkbox.count(), 1);

    await page.evaluate(() => window.openBookmarkDialog());
    await page.locator('#bookmark-title-input').fill('保存失敗リンク');
    await page.locator('#bookmark-url-input').fill('https://example.com/failure');
    await page.evaluate(() => window.rejectHomeSave = true);
    const bookmarkState = () => page.evaluate(async () => structuredClone((await import('./js/config.js?v=9.0')).userConfig.bookmarks));
    const originalBookmarks = await bookmarkState();
    await page.locator('#bookmark-dialog [type=submit]').click();
    assert.equal(await page.locator('#bookmark-title-input').inputValue(), '保存失敗リンク');
    assert.equal(await page.locator('#bookmark-dialog').evaluate(e => e.inert), false);
    assert.deepEqual(await bookmarkState(), originalBookmarks);
    await page.evaluate(() => window.rejectHomeSave = false);
    await page.locator('#bookmark-dialog [type=submit]').click();
    const savedBookmarks = await bookmarkState();
    await page.evaluate(() => window.rejectHomeSave = true);
    await page.evaluate(() => window.deleteBookmark(0));
    assert.deepEqual(await bookmarkState(), savedBookmarks, 'failed bookmark deletion rolls back');
    await page.evaluate(() => window.rejectHomeSave = false);
    await page.evaluate(() => window.deleteBookmark(0));
    await page.evaluate(() => window.rejectHomeSave = true);
    await page.evaluate(() => window.undoDeleteBookmark());
    assert.equal((await bookmarkState()).length, savedBookmarks.length - 1);
    await page.evaluate(() => window.rejectHomeSave = false);
    await page.evaluate(() => window.undoDeleteBookmark());
    assert.deepEqual(await bookmarkState(), savedBookmarks);
    await page.evaluate(() => window.rejectHomeSave = true);
    await page.evaluate(() => window.reorderBookmark(0, 1));
    assert.deepEqual(await bookmarkState(), savedBookmarks, 'failed reorder rolls back');
    await page.evaluate(() => window.openFolderDialog());
    await page.locator('#bookmark-title-input').fill('保存失敗フォルダ');
    await page.locator('#bookmark-dialog [type=submit]').click();
    assert.equal(await page.locator('#bookmark-title-input').inputValue(), '保存失敗フォルダ');
    assert.deepEqual(await bookmarkState(), savedBookmarks);
    console.log('PASS: failed task/bookmark create, complete, delete, undo, reorder and folder creation preserve data and allow retry');
}).catch(error => { console.error(error); process.exitCode = 1; });
