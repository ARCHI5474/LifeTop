const assert = require('node:assert/strict');
const { withApp } = require('./helpers/browser.cjs');

withApp(async page => {
    await page.locator('#todo-input').fill('共同タスク');
    await page.locator('#todo-input').press('Enter');
    await page.locator('#home-calendar-card').click();
    await page.getByRole('button',{name:'予定を作成',exact:true}).click();
    const form = page.locator('dialog.cc-form-dialog form');
    await form.locator('[name=title]').fill('打ち合わせ');
    await form.locator('[name=repeat]').selectOption('weekly');
    await form.locator('[type=submit]').click();
    await page.locator('dialog.cc-form-dialog').waitFor({state:'detached'});
    await page.locator('.cc-agenda-event').filter({hasText:'打ち合わせ'}).waitFor();
    await page.keyboard.press('Escape');
    await page.locator('#cc-dialog').waitFor({state:'detached'});
    await page.keyboard.press('Control+k');
    await page.locator('#cc-query').fill('共同');
    await page.locator('[data-cc=result-task]').filter({hasText:'共同タスク'}).waitFor();
    await page.keyboard.press('Escape');
    await page.reload();
    await page.locator('#todo-list').filter({hasText:'共同タスク'}).waitFor();
    const stored = await page.evaluate(async () => {
        const m = await import('./js/canvas-model.js');
        const a = await m.readCanvas(), stale = structuredClone(a);
        await m.commitCanvas(a, a.revision);
        let conflict = false;
        try { await m.commitCanvas(stale, stale.revision); } catch { conflict = true; }
        return {events:a.events.length, repeat:a.events[0].repeat, conflict};
    });
    assert.deepEqual(stored, {events:1, repeat:'weekly', conflict:true});
    await page.goto('http://localhost/mini-apps.html#document');
    await page.locator('#editor').fill('保存テスト');
    await page.locator('#mini-name').fill('文書A');
    await page.locator('#studio-workspace-save').click();
    await page.locator('#mini-status').filter({hasText:'ファイル一覧に保存しました'}).waitFor();
    await page.locator('#editor').fill('変更後');
    await page.waitForTimeout(600);
    await page.locator('#studio-undo').click();
    assert.equal(await page.locator('#editor').innerText(), '保存テスト');
    await page.locator('#studio-redo').click();
    assert.equal(await page.locator('#editor').innerText(), '変更後');
    await page.locator('#studio-template-save').click();
    await page.locator('#studio-template option').nth(1).waitFor({state:'attached'});
    await page.locator('#studio-new').click();
    await page.locator('#editor').fill('文書B本文');
    await page.locator('#mini-name').fill('文書B');
    await page.locator('#studio-workspace-save').click();
    await page.locator('#mini-status').filter({hasText:'ファイル一覧に保存しました'}).waitFor();
    const files = await page.evaluate(async () => (await (await import('./js/canvas-model.js')).readCanvas()).files);
    assert.equal(files.length, 3);
    await page.goto('http://localhost/mini-apps.html?file=' + files[0].id + '#document');
    await page.locator('#editor').waitFor();
    assert.equal(await page.locator('#editor').innerText(), '変更後');
    await page.goto('http://localhost/messages.html#invite=untrusted');
    await page.locator('#messages-setup').waitFor();
    assert.equal(await page.locator('#messages-controls').isVisible(), false);
    assert.equal(new URL(page.url()).hash, '');
    console.log('PASS: calendar/task/search persistence, stale write protection, Studio undo/redo/templates/multiple files and unconfigured Messages');
}).catch(error => {console.error(error); process.exitCode = 1;});
