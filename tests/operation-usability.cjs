const assert=require('node:assert/strict');
const {withApp}=require('./helpers/browser.cjs');
withApp(async(page,context)=>{
    await context.route(/\/js\/festival-config\.js(?:\?.*)?$/,route=>route.fulfill({contentType:'text/javascript',body:'export const festivalConfig={startAt:null,durationDays:10};'}));
    await page.reload();
    await page.locator('.dashboard-header [aria-label="Studioを開く"]').click();
    const studio=page.locator('#mini-app-dialog [data-view=studio]');
    await studio.focus();await page.keyboard.press('ArrowRight');
    assert.equal(await page.locator('#mini-app-dialog [data-view=games]').getAttribute('aria-selected'),'true','arrow key switches the Studio tabs');
    await page.waitForTimeout(100);
    assert.equal(await page.locator('#mini-app-dialog [data-view=games]').evaluate(e=>e===document.activeElement),true,'tab switching must not steal focus after a delay');
    await page.keyboard.press('Home');
    const frame=page.frameLocator('#mini-app-dialog iframe');
    await frame.locator('[data-app=document]').click();
    await frame.locator('#editor').fill('日本語入力を維持');
    await frame.locator('#editor').dispatchEvent('keydown',{key:'Escape',isComposing:true,keyCode:229});
    await page.waitForTimeout(250);
    assert.equal(await page.locator('#mini-app-dialog[open]').count(),1,'IME Escape must not close the editor');
    await page.locator('#mini-app-dialog [data-cancel]').click();
    await page.locator('#mini-app-dialog').waitFor({state:'detached'});
    await page.evaluate(()=>window.openBookmarkDialog());
    await page.locator('#bookmark-title-input').fill('まだ保存していないリンク');
    page.once('dialog',dialog=>dialog.dismiss());
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#bookmark-title-input').inputValue(),'まだ保存していないリンク');
    assert.equal(await page.locator('#bookmark-dialog').evaluate(e=>e.inert),false,'cancelled discard keeps the form open');
    page.once('dialog',dialog=>dialog.accept());
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#bookmark-dialog').evaluate(e=>e.inert),true);
    console.log('PASS: Studio tab keyboard navigation, composition Escape and bookmark draft protection');
}).catch(error=>{console.error(error);process.exitCode=1;});
