import assert from 'node:assert/strict';
import { userConfig, DEFAULT_SETTINGS, STORAGE_KEY } from '../js/config.js?v=8.0';
import { createBackup, parseBackup, resetSettingsSnapshot, storeSnapshot, MAX_BACKUP_BYTES } from '../js/data-management.js?v=8.0';

const source = structuredClone(userConfig);
source.username = 'テスト';
source.theme = '#E040FB';
source.textSize = 'large';
source.memo = '大切なメモ';
source.memoHtml = '<b>大切なメモ</b>';
source.todoList = [{id: 99, text:'残しておくタスク', completed:false, priority:true}];
source.bookmarks = [{id:'folder_1',type:'folder',title:'資料',children:[{title:'example',url:'https://example.com/'}]}];
const before = structuredClone(source);
const text = createBackup(source);
assert.deepEqual(parseBackup(text), source, 'Japanese content, rich memo, folder children and settings survive a round trip');
assert.deepEqual(source,before,'creating and validating a backup does not mutate data');
const reset = resetSettingsSnapshot(source);
for (const [key, value] of Object.entries(DEFAULT_SETTINGS)) assert.equal(reset[key],value);
for (const key of ['memo','memoHtml','todoList','bookmarks']) assert.deepEqual(reset[key],source[key]);
assert.equal(source.textSize,'large','reset builds a candidate without applying it');
assert.throws(()=>parseBackup('{broken'),/JSON/);
assert.throws(()=>parseBackup('{}'),/LifeTop/);
const corrupted = change => {
    const envelope = JSON.parse(text); change(envelope); return JSON.stringify(envelope);
};
assert.throws(()=>parseBackup(corrupted(b=>b.version=2)),/LifeTop/);
assert.throws(()=>parseBackup(corrupted(b=>delete b.data.memo)),/形式/);
assert.throws(()=>parseBackup(corrupted(b=>b.data.textSize='huge')),/設定値/);
assert.throws(()=>parseBackup(corrupted(b=>b.data.todoList.push(b.data.todoList[0]))),/識別番号/);
assert.throws(()=>parseBackup(corrupted(b=>b.data.bookmarks[0].children[0].url='javascript:alert(1)')),/フォルダ/);
assert.throws(()=>parseBackup(corrupted(b=>b.data.bookmarks[0].id="folder');alert(1)")),/フォルダ/);
assert.throws(()=>parseBackup(text.replace('"data": {','"data": {"__proto__": {},')),/JSON/);
assert.throws(()=>parseBackup(' '.repeat(MAX_BACKUP_BYTES+1)),/10MB/);
let persisted = 'existing data';
assert.throws(()=>storeSnapshot(reset,{setItem(){throw new Error('quota');}}),/quota/);
assert.equal(persisted,'existing data');
storeSnapshot(parseBackup(text),{setItem(key,value){assert.equal(key,STORAGE_KEY);persisted=value;}});
assert.deepEqual(JSON.parse(persisted),source,'restore persists the whole snapshot in one write');
console.log('PASS: backup round trip, reset preserves content, malformed files, unsafe URLs, duplicate IDs, size limit and atomic storage');
